import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REGISTER = ROOT / "docs" / "registers" / "goetia.json"
OUTPUT = ROOT / "docs" / "registers" / "goetia.md"
RUDD = ROOT / "docs" / "sources" / "rudd" / "72-seals-and-angels.md"

KINDS = {
    "PRAETERITA", "PRAESENTIA", "FUTURA", "OCCULTA", "THESAURI", "AMISSA", "RESPONSA", "DOCTRINA",
    "LINGUAE", "VIRTUTES", "CONCORDIA", "DISCORDIA", "DIGNITATES", "FAMILIARES", "VECTIO", "FURTUM",
    "INVISIBILITAS", "ILLUSIO", "TRANSMUTATIO", "AEDIFICATIO", "EVERSIO", "TEMPESTAS", "NEX", "MORBUS",
    "MORTUI", "MENS", "CUSTODIA", "CONSECRATIO", "TUTELA", "LONGAEVITAS", "APPELLATIO", "PROBATIO", "NULLUM",
}
ARTES = {
    "grammatica", "dialectica", "rhetorica", "arithmetica", "geometria", "musica", "astronomia",
    "astrologia", "mechanica", "philosophia", "poetica", "chiromantia", "pyromantia",
}
VERACITY = {"VERAX", "COACTUS", "MENDAX", "FIDUS", "TACITUS"}
WITNESSES = {"W", "S", "G", "M", "K", "F", "A"}
QUARTER_KINGS = {"East": "Amaymon", "South": "Gorson", "North": "Zymymar", "West": "Goap"}
RANKS = {"king", "duke", "prince", "marquis", "president", "earl", "knight"}
INK = {"king": "rex", "duke": "dux", "prince": "princeps", "marquis": "marchio",
       "president": "praeses", "earl": "comes", "knight": "eques"}


def angels():
    text = RUDD.read_text(encoding="utf-8")
    block = re.search(r"```json\n(.*?)\n```", text, re.S).group(1)
    return {pair["n"]: pair["angel"] for pair in json.loads(block)["pairs"]}


def outcomes(spirit):
    result = ["OBSEQUIUM", "MORA", "PARS", "RECUSATIO"]
    if spirit["veracity"] in ("COACTUS", "MENDAX", "TACITUS"):
        result.append("MENDACIUM")
    if spirit["veracity"] != "FIDUS" and spirit["malice"]:
        result.append("MALITIA")
    return result


def validate(register):
    errors = []
    if [s["n"] for s in register] != list(range(1, 73)):
        errors.append("register must hold spirits 1 to 72 in order")
    for s in register:
        tag = f"{s['n']} {s['name']}"
        if not set(s["rank"].split("/")) <= RANKS:
            errors.append(f"{tag}: unknown rank {s['rank']}")
        if not isinstance(s["legions"], int) or s["legions"] < 1:
            errors.append(f"{tag}: legions must be a positive number")
        if s["legions_witness"] not in WITNESSES:
            errors.append(f"{tag}: unknown legions witness")
        if s["veracity"] not in VERACITY:
            errors.append(f"{tag}: unknown veracity {s['veracity']}")
        if s["veracity"] != "TACITUS" and not s["veracity_condition"]:
            errors.append(f"{tag}: veracity {s['veracity']} needs its stated condition")
        if not s["offices"]:
            errors.append(f"{tag}: no offices")
        for group in ("offices", "malice", "counterbalances", "notes"):
            for item in s[group]:
                if item["witness"] not in WITNESSES:
                    errors.append(f"{tag}: {group} item without a known witness")
        for office in s["offices"]:
            if office["kind"] not in KINDS:
                errors.append(f"{tag}: unknown office kind {office['kind']}")
            artes = office.get("artes")
            if office["kind"] == "DOCTRINA":
                if not artes or any(a not in ARTES for a in artes) or len(set(artes)) != len(artes):
                    errors.append(f"{tag}: a DOCTRINA office needs its arts (offices.md §5.1)")
            elif artes is not None:
                errors.append(f"{tag}: only DOCTRINA names arts")
    return errors


def render(register, names):
    lines = [
        "# Register of the 72 Spirits (`goetia`, `rudd`)",
        "",
        "Generated by `tools/build_register.py` from `goetia.json`. Do not edit by hand. Rules: `docs/spec/spirits.md`.",
        "",
        "Witnesses: **W** Weyer 1577, **S** Sloane 3825, **G** 1904 edition. **F** Folger V.b.26 (Book of Oberon), **A** Ad. 36674. **M** marks the owner's rulings: original to Annulus, not tradition. A spirit's king is the `goetia` king of his stated quarter (ruling 2026-11-10).",
        "",
        "## Summary",
        "",
        "| # | Spirit | Rank (S) | Ink | Legions | Quarter, king | Veracity | Will may choose | Examiner (`rudd`) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for s in register:
        ranks = s["rank"].split("/")
        ink = " / ".join(f'"{INK[r]}"' for r in ranks)
        lines.append(
            f"| {s['n']} | {s['name']} | {s['rank'].replace('/', ' and ')} | {ink} | "
            f"{s['legions']} ({s['legions_witness']}) | "
            f"{(s['quarter']['value'] + ', ' + QUARTER_KINGS[s['quarter']['value']]) if s.get('quarter') else '—'} | `{s['veracity']}` | "
            f"{', '.join('`' + o + '`' for o in outcomes(s))} | {names.get(s['n'], '?')} |")
    lines += ["", "## Entries", ""]
    for s in register:
        lines.append(f"### {s['n']}. {s['name']}")
        lines.append("")
        if s["aliases"]:
            lines.append(f"Also: {', '.join(s['aliases'])}.")
            lines.append("")
        rank = s["rank"].replace("/", " and ")
        variant = f"; variant: {s['rank_variants']}" if s["rank_variants"] else ""
        quarter = s.get("quarter")
        king = (f" **Quarter:** {quarter['value']} ({quarter['witness']}), so his king is "
                f"{QUARTER_KINGS[quarter['value']]}." if quarter else " **Quarter:** not stated; his king is unknown.")
        lines.append(f"**Rank:** {rank} (S){variant}. **Legions:** {s['legions']} ({s['legions_witness']}). "
                     f"**Examiner:** {names.get(s['n'], '?')} (Shem angel {s['n']}).{king}")
        lines.append("")
        cond = f": {s['veracity_condition']}" if s["veracity_condition"] else ""
        lines.append(f"**Veracity:** `{s['veracity']}`{cond}.")
        lines.append("")
        lines.append("**Offices:**")
        lines.append("")
        for o in s["offices"]:
            artes = f" *Arts:* {', '.join(o['artes'])}." if o.get("artes") else ""
            lines.append(f"- `{o['kind']}` ({o['witness']}): {o['text']}{artes}")
        lines.append("")
        if s["malice"]:
            lines.append("**Malice:**")
            lines.append("")
            for m in s["malice"]:
                lines.append(f"- ({m['witness']}) {m['text']}")
            lines.append("")
        if s["counterbalances"]:
            lines.append("**Counterbalances and wards:**")
            lines.append("")
            for c in s["counterbalances"]:
                lines.append(f"- ({c['witness']}) {c['text']}")
            lines.append("")
        if s["notes"]:
            lines.append("**Notes:**")
            lines.append("")
            for n in s["notes"]:
                lines.append(f"- ({n['witness']}) {n['text']}")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


NAMES = ROOT / "docs" / "registers" / "nomina.json"
KINGS = ROOT / "docs" / "registers" / "reges.json"
NAME_KINDS = {"deus", "angelus", "ordo", "sephira", "sphaera", "figura"}


def validate_names(names):
    errors = []
    for entry in names:
        if entry["kind"] not in NAME_KINDS:
            errors.append(f"name {entry['n']}: unknown kind {entry['kind']}")
        if not entry["forms"]:
            errors.append(f"name {entry['n']}: no forms")
        for form in entry["forms"]:
            if form["witness"] not in WITNESSES:
                errors.append(f"name {entry['n']}: form without a known witness")
    return errors


def validate_kings(kings):
    errors = []
    for rite in {k["rite"] for k in kings}:
        quarters = sorted(k["quarter"] for k in kings if k["rite"] == rite)
        if quarters != ["East", "North", "South", "West"]:
            errors.append(f"kings of {rite}: need exactly one king per quarter")
    return errors


def render_names(names):
    lines = [
        "# Register of Divine and Sacred Names",
        "",
        "Generated by `tools/build_register.py` from `nomina.json`. Do not edit by hand. Only entries of kind `deus` may be cited by `NOMEN` or `CONSTRINGE … PER NOMEN`; any recorded form matches (`static.md` §4.13).",
        "",
        "Witnesses: **S** Sloane 3825 (the figures read from the manuscript; the First Conjuration via Peterson's transcription), **G** 1904 edition, filling only what the manuscript leaves illegible.",
        "",
        "| # | Kind | Forms | Where | Note |",
        "|---|---|---|---|---|",
    ]
    for e in names:
        forms = "; ".join(f"{f['text']} ({f['witness']})" for f in e["forms"])
        where = e["place"] + (f", segment {e['segment']}" if e["segment"] else "")
        lines.append(f"| {e['n']} | `{e['kind']}` | {forms} | {where} | {e['note'] or ''} |")
    return "\n".join(lines) + "\n"


def render_kings(kings):
    lines = [
        "# Register of the Four Kings",
        "",
        "Generated by `tools/build_register.py` from `reges.json`. Do not edit by hand. Each rite has its own four; neither set overrides the other (`authority.md` §4).",
        "",
        "Witnesses: **W** Weyer 1577, **S** Sloane 3825, **G** 1904 edition, **K** the Key, BnF Ital. 1524 (1446).",
        "",
        "| # | Rite | Quarter | Names | Deciding witness | Spirits under him |",
        "|---|---|---|---|---|---|",
    ]
    for k in kings:
        names = "; ".join(f"{x['text']} ({x['witness']})" for x in k["names"])
        subjects = "; ".join(f"{x['spirit']} ({x['source']})" for x in k["subjects"]) or "none stated"
        lines.append(f"| {k['n']} | `{k['rite']}` | {k['quarter']} | {names} | {k['witness']} | {subjects} |")
    return "\n".join(lines) + "\n"


def main():
    register = json.loads(REGISTER.read_text(encoding="utf-8"))
    names = json.loads(NAMES.read_text(encoding="utf-8"))
    kings = json.loads(KINGS.read_text(encoding="utf-8"))
    errors = validate(register) + validate_names(names) + validate_kings(kings)
    for error in errors:
        print(error)
    if errors:
        return 1
    OUTPUT.write_text(render(register, angels()), encoding="utf-8")
    NAMES.with_suffix(".md").write_text(render_names(names), encoding="utf-8")
    KINGS.with_suffix(".md").write_text(render_kings(kings), encoding="utf-8")
    print(f"{len(register)} spirits, {len(names)} names, {len(kings)} kings written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
